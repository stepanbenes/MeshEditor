	/// <summary>
	/// JSON written and read by System.Text.Json is compared with the reference written and read by Newtonsoft.Json
	/// (TestData/NewtonsoftJsonReference.txt, generated by this test with the previous Newtonsoft.Json implementation).
	/// Set the environment variable MESHEDITOR_JSON_REFERENCE_OUTPUT to a file path to write the current results there.
	/// </summary>
	public class JsonCompatibilityTests
	{
		private const string ReferenceOutputEnvironmentVariable = "MESHEDITOR_JSON_REFERENCE_OUTPUT";

		/// <summary>
		/// Intended differences from the reference.
		/// </summary>
		private static readonly Dictionary<string, string> knownDifferences = new Dictionary<string, string>
		{
			["read_decimal_keys"] = "dictionary key \"1E-05\" is read, Newtonsoft.Json failed",
			["read_single_quotes"] = "System.Text.Json does not read single-quoted strings (never written, only in hand-edited files)",
			["config_reload"] = "decimal read back from the configuration keeps its scale (2.0), Newtonsoft.Json read it through double (2)",
		};

		public enum SampleEnum { Zero, One, Two }

		public class ConfigSample
		{
			public Color Named { get; set; }
			public Color Custom { get; set; }
			public Color Translucent { get; set; }
			public Color Empty { get; set; }
			public SampleEnum Enum { get; set; }
			public float Float { get; set; }
			public double Double { get; set; }
			public decimal Decimal { get; set; }
			public string Text { get; set; }
			public int[] Numbers { get; set; }
			public DateTime Date { get; set; }
			public Guid Guid { get; set; }
			public string ReadOnly => "ro";
		}

		static string ser<T>(T obj)
		{
			var s = new JsonSerializationService();
			var ms = new MemoryStream();
			s.Serialize(obj, ms);
			return System.Text.Encoding.UTF8.GetString(ms.ToArray());
		}

		static string roundtrip<T>(string json)
		{
			var s = new JsonSerializationService();
			var obj = s.Deserialize<T>(new MemoryStream(System.Text.Encoding.UTF8.GetBytes(json)));
			return ser(obj);
		}

		static string roundtrip2<T>(byte[] json)
		{
			var obj = new JsonSerializationService().Deserialize<T>(new MemoryStream(json));
			return ser(obj);
		}

		class PrivateSettings
		{
			public int Width { get; set; } = 800;
			public SampleEnum State { get; set; } = SampleEnum.One;
			public string Last { get; set; }
		}

		static string tryIt(Func<string> f)
		{
			try { return f(); }
			catch (Exception e) { return "EXCEPTION " + e.GetType().Name + ": " + e.Message; }
		}

		private static string testDataPath(string fileName) => Path.Combine(AppContext.BaseDirectory, "TestData", fileName);

		private static Dictionary<string, string> parseResults(string text)
		{
			return text.Replace("\r\n", "\n").Split("##### ", StringSplitOptions.RemoveEmptyEntries)
				.Select(section => section.Split('\n', 2))
				.ToDictionary(parts => parts[0], parts => parts[1].TrimEnd('\n'));
		}

		[Test]
		public void SerializedJsonIsTheSameAsByNewtonsoft()
		{
			string results = runCases();
			string outputPath = Environment.GetEnvironmentVariable(ReferenceOutputEnvironmentVariable);
			if (!string.IsNullOrEmpty(outputPath))
			{
				File.WriteAllText(outputPath, results);
			}

			var actual = parseResults(results);
			var expected = parseResults(File.ReadAllText(testDataPath("NewtonsoftJsonReference.txt")));
			Assert.That(actual.Keys, Is.EquivalentTo(expected.Keys));
			Assert.Multiple(() =>
			{
				foreach (var (name, expectedText) in expected)
				{
					string expectedResult = expectedText;
					string actualResult = actual[name];
					if (knownDifferences.ContainsKey(name))
						continue;
					if (expectedResult.StartsWith("EXCEPTION "))
					{
						Assert.That(actualResult, Does.StartWith("EXCEPTION "), $"{name}: Newtonsoft.Json failed, so should System.Text.Json");
						continue;
					}
					if (name == "config_saved") // contains version of the current assembly
					{
						expectedResult = Regex.Replace(expectedResult, "\"AssemblyVersion\": \"[^\"]*\"", "\"AssemblyVersion\": \"\"");
						actualResult = Regex.Replace(actualResult, "\"AssemblyVersion\": \"[^\"]*\"", "\"AssemblyVersion\": \"\"");
					}
					Assert.That(actualResult, Is.EqualTo(expectedResult), name);
				}
			});
		}

		private static string runCases()
		{
			var cases = new List<(string, Func<string>)>();

			var summary = new SummaryFile
			{
				Id = new Guid("11111111-2222-3333-4444-555555555555"),
				Name = "Řez <a> & 'b' \"q\" +/",
				ParentId = null,
				Filter = FilterFactory.Create(FilterType.Slice, new[] { "0", "0.5", "1", "-2.25" }),
				Meshes = new[]
				{
					new MeshFileDescriptor { Index = 0, TimeSteps = new[] { 0m, 0.5m, 1m, 1.0m, 1.50m, 0.00001m, 123456789.123456789m },
						Attributes = new[] { new DataFileDescriptor { FieldName = "f", ComponentName = null, Index = 2, TimeSteps = null, Location = DataLocationType.CellPoints } } },
				},
				Fields = new Dictionary<string, FieldDescriptor>
				{
					["displacement"] = new FieldDescriptor { Components = new Dictionary<string, ComponentDescriptor> { ["x"] = new ComponentDescriptor { TimeSteps = new Dictionary<decimal, TimeStepDescriptor> { [0m] = new TimeStepDescriptor { MeshIndex = 0, DataIndex = 1 }, [1.0m] = new TimeStepDescriptor(), [0.25m] = new TimeStepDescriptor { DataIndex = 3 } } } } },
				},
				MeshFallbackLayerId = new Guid("aaaaaaaa-2222-3333-4444-555555555555"),
			};
			cases.Add(("summary_slice", () => ser(summary)));
			foreach (var (type, pars) in new (FilterType, string[])[]
			{
				(FilterType.Surface, new[] { "30", "60.5" }),
				(FilterType.AttributeSelection, new[] { "attr", "1", "2", "3" }),
				(FilterType.TimeCompression, new string[0]),
				(FilterType.TimeCompression, new[] { "temp" }),
				(FilterType.Deformation, new[] { "disp" }),
				(FilterType.Deformation, new[] { "disp", "2.5" }),
				(FilterType.IsoSurface, new[] { "temp", "x", "1e-5" }),
			})
			{
				var sf = new SummaryFile { Id = Guid.Empty, Name = "n", Filter = FilterFactory.Create(type, pars), Fields = null };
				cases.Add(($"summary_{type}_{pars.Length}", () => ser(sf)));
			}
			cases.Add(("summary_nofilter", () => ser(new SummaryFile())));

			CompressionParameters[] comps =
			{
				new TransparentCompressionParameters { Rows = 3, Columns = 4 },
				new SVDCompressionParameters { Rows = 3, Columns = 4, Rank = 2 },
				new WaveletCompressionParameters { Rows = 3, Columns = 4, MinDataValue = -1.5, MaxDataValue = double.NaN, Iterations = 3 },
				new WaveletCompressionParameters { MinDataValue = double.NegativeInfinity, MaxDataValue = double.PositiveInfinity },
				new WaveletCompressionParameters { MinDataValue = 1e-300, MaxDataValue = double.MaxValue },
				new WaveletCompressionParameters { MinDataValue = -0.0, MaxDataValue = 0.1 + 0.2 },
			};
			int ci = 0;
			foreach (var c in comps)
			{
				var df = new DataFile
				{
					LayerId = Guid.Empty, Index = 1, MeshIndex = 2, FieldName = "f", ComponentName = ci % 2 == 0 ? null : "c",
					TimeSteps = ci % 2 == 0 ? null : new[] { 1m, 2.5m }, Location = DataLocationType.Points, Compression = c,
					Encoding = new EncodingParameters { DataType = (DataArrayType)(ci % 5), OriginalLength = 10, Offset = 0, Length = 10, DefaultValue = ci % 2 == 0 ? null : "0" },
					Data = "AAEC+/8=",
				};
				cases.Add(($"datafile_{ci++}", () => ser(df)));
			}
			cases.Add(("datafile_empty", () => ser(new DataFile())));

			cases.Add(("meshfile", () => ser(new MeshFile { LayerId = Guid.Empty, Index = 1, NumberOfPoints = 3, NumberOfCells = 1, NumberOfEdges = 0, Center = new[] { 0f, 0.1f, 1f / 3f, 1e10f, -1e-10f }, Radius = 2.5f, PointCoordinates = "AA+/", CellConnectivity = "BB==", CellTypes = null, EdgeConnectivity = "CC" })));

			var solution = new Solution
			{
				Id = 7, ProjectName = "Projekt č. 1 <x>", Location = null,
				Owner = new RemoteUser { Id = "id", Name = "a@b.c" },
				Results = new[] { new AnalysisResult { TimeStep = null, MeshRecordNames = new[] { "m" }, DataRecordNames = new List<string> { "d1", "d2" } }, new AnalysisResult { TimeStep = 0.1m, MeshRecordNames = Enumerable.Empty<string>(), DataRecordNames = null } },
				Layers = new[] { new Solution.Layer { Id = new Guid("00000000-0000-0000-0000-000000000001"), Name = "L", FilterType = "Surface", Children = new[] { new Solution.Layer { Id = new Guid("00000000-0000-0000-0000-000000000002"), Name = "C", FilterType = null } } } },
				LayerFolder = "folder",
			};
			cases.Add(("solution", () => ser(solution)));
			cases.Add(("solutioninfo", () => ser(new SolutionInfo { Id = 1, ProjectName = "p" })));

			// lenient reading
			cases.Add(("read_lowercase", () => roundtrip<SummaryFile>("{\"id\":\"11111111-2222-3333-4444-555555555555\",\"name\":\"x\",\"filter\":{\"type\":\"Slice\",\"normalx\":1.5}}")));
			cases.Add(("read_filter_type_last", () => roundtrip<SummaryFile>("{\"Filter\":{\"NormalX\":1.5,\"Type\":\"Slice\"}}")));
			cases.Add(("read_filter_type_lowercase_value", () => roundtrip<SummaryFile>("{\"Filter\":{\"Type\":\"slice\"}}")));
			cases.Add(("read_filter_type_number", () => roundtrip<SummaryFile>("{\"Filter\":{\"Type\":1}}")));
			cases.Add(("read_filter_type_number_string", () => roundtrip<SummaryFile>("{\"Filter\":{\"Type\":\"1\"}}")));
			cases.Add(("read_filter_type_missing", () => roundtrip<SummaryFile>("{\"Filter\":{\"NormalX\":1}}")));
			cases.Add(("read_filter_null", () => roundtrip<SummaryFile>("{\"Filter\":null}")));
			cases.Add(("read_filter_unsupported", () => roundtrip<SummaryFile>("{\"Filter\":{\"Type\":\"Clip\"}}")));
			cases.Add(("read_compression_wt", () => roundtrip<DataFile>("{\"Compression\":{\"Method\":\"WT\",\"MinDataValue\":\"NaN\",\"MaxDataValue\":\"Infinity\",\"Iterations\":2}}")));
			cases.Add(("read_compression_default_alias", () => roundtrip<DataFile>("{\"Compression\":{\"Method\":\"Default\"}}")));
			cases.Add(("read_location_number", () => roundtrip<DataFile>("{\"Location\":2,\"Encoding\":{\"DataType\":\"float32\"}}")));
			cases.Add(("read_location_lowercase", () => roundtrip<DataFile>("{\"Location\":\"cells\"}")));
			cases.Add(("read_numbers_as_strings", () => roundtrip<DataFile>("{\"Index\":\"5\",\"TimeSteps\":[\"1.5\",2]}")));
			cases.Add(("read_float_into_int", () => roundtrip<DataFile>("{\"Index\":5.0}")));
			cases.Add(("read_comments", () => roundtrip<DataFile>("/* c */ {\"Index\":5 // x\n}")));
			cases.Add(("read_trailing_comma", () => roundtrip<DataFile>("{\"Index\":5,\"TimeSteps\":[1,2,],}")));
			cases.Add(("read_unknown_props", () => roundtrip<DataFile>("{\"Foo\":{\"a\":[1,2]},\"Index\":5}")));
			cases.Add(("read_decimal_exponent", () => roundtrip<DataFile>("{\"TimeSteps\":[1E-05,1.0e2]}")));
			cases.Add(("read_decimal_keys", () => roundtrip<SummaryFile>("{\"Fields\":{\"f\":{\"Components\":{\"x\":{\"TimeSteps\":{\"1.0\":{\"MeshIndex\":1},\"1E-05\":{\"MeshIndex\":2},\"0.50\":{}}}}}}}")));
			cases.Add(("read_bom", () => roundtrip<DataFile>("\uFEFF{\"Index\":5}")));
			cases.Add(("read_single_quotes", () => roundtrip<DataFile>("{'Index':5}")));
			cases.Add(("read_nested_layers", () => roundtrip<Solution>("{\"Id\":3,\"Layers\":[{\"Id\":\"00000000-0000-0000-0000-000000000001\",\"Name\":\"a\",\"Children\":[{\"Id\":\"00000000-0000-0000-0000-000000000002\",\"Name\":\"b\",\"Children\":[]}]}],\"Owner\":{\"Id\":\"x\"}}")));
			cases.Add(("read_solutioninfo_from_solution", () => roundtrip<SolutionInfo>(ser(solution))));
			cases.Add(("read_solution_roundtrip", () => roundtrip<Solution>(ser(solution))));
			cases.Add(("read_summary_roundtrip", () => roundtrip<SummaryFile>(ser(summary))));
			cases.Add(("read_empty", () => (new JsonSerializationService().Deserialize<DataFile>(new MemoryStream()) == null).ToString()));
			cases.Add(("read_json_null", () => (new JsonSerializationService().Deserialize<DataFile>(new MemoryStream(System.Text.Encoding.UTF8.GetBytes("null"))) == null).ToString()));
			cases.Add(("read_utf16_bom", () => roundtrip2<DataFile>(System.Text.Encoding.Unicode.GetPreamble().Concat(System.Text.Encoding.Unicode.GetBytes("{\"FieldName\":\"ž\"}")).ToArray())));
			cases.Add(("read_null_into_int", () => roundtrip<DataFile>("{\"Index\":null}")));
			cases.Add(("read_duplicate_props", () => roundtrip<DataFile>("{\"Index\":1,\"Index\":2}")));
			cases.Add(("read_date_string_guid", () => roundtrip<DataFile>("{\"LayerId\":\"{11111111-2222-3333-4444-555555555555}\"}")));

			// configuration manager
			var dir = Path.Combine(Path.GetTempPath(), "MeshEditorTests", Guid.NewGuid().ToString("N"));
			Directory.CreateDirectory(dir);
			var orig = ConfigurationManager.ConfigurationDirectory;
			try
			{
				ConfigurationManager.ConfigurationDirectory = dir;
				File.WriteAllText(Path.Combine(dir, "config.json"), "{\"AssemblyVersion\":\"999.0.0.0\",\"Sample\":{\"Named\":\"Red\",\"Custom\":\"10, 20, 30\",\"Translucent\":\"128, 10, 20, 30\",\"Enum\":\"two\",\"Float\":1,\"Text\":\"ž\"},\"LocalStorage\":{\"directory\":\"C:\\\\x\"},\"AzureBlobStorage\":{\"AccountUrl\":\"u\",\"IsComplete\":true}}");
				ConfigurationManager.LoadConfiguration();
				var sample = ConfigurationManager.GetConfigurationObject<ConfigSample>("Sample");
				cases.Add(("config_get_sample", () => FormattableString.Invariant($"{sample.Named} {sample.Custom} {sample.Translucent} {sample.Empty} {sample.Enum} {sample.Float} {sample.Text}")));
				var ls = ConfigurationManager.GetConfigurationObject<LocalStorageConfiguration>("LocalStorage");
				cases.Add(("config_get_local", () => ls.Directory));
				var az = ConfigurationManager.GetConfigurationObject<AzureBlobStorageConfiguration>("AzureBlobStorage");
				cases.Add(("config_get_azure", () => FormattableString.Invariant($"{az.AccountUrl} {az.SolutionsBlobContainerName} {az.IsComplete}")));
				cases.Add(("config_get_missing", () => (ConfigurationManager.GetConfigurationObject<ConfigSample>("Missing") == null).ToString()));
				cases.Add(("config_get_string_dict", () => tryIt(() => string.Join(",", ConfigurationManager.GetConfigurationObject<Dictionary<string, string>>("LocalStorage")))));
				ConfigurationManager.SetConfigurationObject("Sample2", new ConfigSample
				{
					Named = Color.Red, Custom = Color.FromArgb(10, 20, 30), Translucent = Color.FromArgb(128, 10, 20, 30), Empty = Color.Empty,
					Enum = SampleEnum.Two, Float = 1.5f, Double = 1, Decimal = 2m, Text = "ž<>&'+", Numbers = new[] { 1, 2 },
					Date = new DateTime(2020, 1, 2, 3, 4, 5, 678, DateTimeKind.Utc), Guid = Guid.Empty,
				});
				ConfigurationManager.SetConfigurationObject("SystemColor", new { C = SystemColors.Control, K = Color.FromKnownColor(KnownColor.AliceBlue) });
				ConfigurationManager.SetConfigurationObject("Private", new PrivateSettings { Width = 5, State = SampleEnum.Two, Last = "x" });
				ConfigurationManager.SetConfigurationObject("Strings", new Dictionary<string, string> { ["1"] = "FF00FF00" });
				ConfigurationManager.SetConfigurationObject("Azure", new AzureBlobStorageConfiguration());
				ConfigurationManager.Save();
				string saved = File.ReadAllText(Path.Combine(dir, "config.json"));
				cases.Add(("config_saved", () => saved));
				ConfigurationManager.LoadConfiguration();
				var s2 = ConfigurationManager.GetConfigurationObject<ConfigSample>("Sample2");
				var p2 = ConfigurationManager.GetConfigurationObject<PrivateSettings>("Private");
				cases.Add(("config_reload_private", () => FormattableString.Invariant($"{p2.Width} {p2.State} {p2.Last}")));
				cases.Add(("config_reload", () => FormattableString.Invariant($"{s2.Named} {s2.Custom} {s2.Translucent} {s2.Empty} {s2.Enum} {s2.Float} {s2.Double} {s2.Decimal} {s2.Text} {s2.Date:o} {s2.Date.Kind}")));
			}
			finally
			{
				ConfigurationManager.ConfigurationDirectory = orig;
			}

			var sb = new StringBuilder();
			foreach (var (name, f) in cases)
			{
				sb.Append("##### ").Append(name).Append('\n');
				sb.Append(tryIt(f)).Append('\n');
			}
			try
			{
				Directory.Delete(dir, recursive: true);
			}
			catch (IOException)
			{ }
			return sb.ToString();
		}
	}
